export function getUtilitiesByGroup(groupId: string): UtilityDefinition[] {
  return utilities.filter((u) => u.groupId === groupId)
}

export function getUtilityById(id: string): UtilityDefinition | undefined {
  return utilities.find((u) => u.id === id)
}

export function getGroupById(id: string): UtilityGroup | undefined {
  return utilityGroups.find((g) => g.id === id)
}
